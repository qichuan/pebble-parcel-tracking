// Packs Ship24's courier list into docs/couriers.js, the data behind the
// courier picker on the settings page. Not shipped to the watch.
//
//   node gen-couriers.js [path/to/couriers.csv]
//
// Refresh the CSV from Ship24 (GET /public/v1/couriers, or the dashboard's
// courier list export) into data/ship24-couriers.csv and re-run this.
const fs = require('fs');
const path = require('path');

const CSV = process.argv[2] ||
  path.join(__dirname, 'data', 'ship24-couriers.csv');
const OUT = path.join(__dirname, '..', 'docs', 'couriers.js');

// Minimal RFC4180 reader — the export quotes every field and has no embedded
// newlines, but doubled quotes inside a field are still handled.
function parseCsv(text) {
  const rows = [];
  let row = [], field = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"') {
        if (text[i + 1] === '"') { field += '"'; i++; } else { quoted = false; }
      } else { field += c; }
    } else if (c === '"') { quoted = true;
    } else if (c === ',') { row.push(field); field = '';
    } else if (c === '\n') { row.push(field); rows.push(row); row = []; field = '';
    } else if (c !== '\r') { field += c; }
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows;
}

// Latin letters with diacritics folded to ASCII, so "ceska" finds "Česká pošta"
// in a webview with no Intl.Normalizer to lean on.
function fold(s) {
  return s.normalize('NFD').replace(/[̀-ͯ]/g, '')
          .replace(/[đĐ]/g, 'd').replace(/[łŁ]/g, 'l')
          .replace(/[øØ]/g, 'o').replace(/[æÆ]/g, 'ae')
          .replace(/[ßẞ]/g, 'ss').replace(/[þÞ]/g, 'th')
          .replace(/[əƏ]/g, 'e');
}

const rows = parseCsv(fs.readFileSync(CSV, 'utf8'));
const head = rows.shift().map((h) => h.trim());
const col = {};
head.forEach((h, i) => { col[h] = i; });
for (const needed of ['code', 'name', 'is_deprecated']) {
  if (col[needed] === undefined) {
    console.error('missing column "' + needed + '" in ' + CSV);
    process.exit(1);
  }
}

const couriers = [];
const seen = {};
for (const r of rows) {
  const code = (r[col.code] || '').trim();
  const name = (r[col.name] || '').trim();
  if (!code || !name) continue;
  if ((r[col.is_deprecated] || '').trim() === '1') continue; // deprecated: hide
  if (name.indexOf('|') !== -1 || name.indexOf('\n') !== -1) {
    console.error('name contains a separator, would corrupt the packing: ' + name);
    process.exit(1);
  }
  if (seen[code]) continue;
  seen[code] = true;
  couriers.push({ code: code, name: name });
}
couriers.sort((a, b) => a.name.localeCompare(b.name, 'en'));

// "name|code", plus an ASCII search key as a third field only where the name
// isn't already ASCII — 22 rows out of 1600-odd, so it costs almost nothing.
const packed = couriers.map((c) => {
  const ascii = fold(c.name);
  return ascii === c.name ? c.name + '|' + c.code
                          : c.name + '|' + c.code + '|' + ascii.toLowerCase();
}).join('\n');

const d = fs.statSync(CSV).mtime;
const stamp = d.getFullYear() + '-' +
  String(d.getMonth() + 1).padStart(2, '0') + '-' +
  String(d.getDate()).padStart(2, '0');
fs.writeFileSync(OUT,
  '/* Ship24 couriers, ' + couriers.length + ' active (deprecated ones removed).\n' +
  '   Generated by tools/gen-couriers.js from ' + path.basename(CSV) + ' (' + stamp + ').\n' +
  '   Do not edit by hand.\n' +
  '   Format: one courier per line, "name|code" — plus "|ascii" when the name\n' +
  '   carries accents, so the picker can match unaccented typing. */\n' +
  'window.COURIERS = ' + JSON.stringify(packed) + ';\n', 'utf8');

console.log('wrote ' + path.relative(path.join(__dirname, '..'), OUT) + ': ' +
            couriers.length + ' couriers, ' +
            Math.round(fs.statSync(OUT).size / 1024) + ' KB');
